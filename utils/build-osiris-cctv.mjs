/**
 * Build vendor/osiris/cctv.cjs from OSIRIS's camera adapters.
 *
 * OSIRIS (MIT, https://github.com/simplifaisoul/osiris) keeps ~100 adapters,
 * one per road agency or camera publisher, under src/app/api/cctv. This
 * compiles them into one CommonJS file the server can require, with no
 * runtime dependencies, and changes how they reach the network:
 *
 *  - stealthFetch (random browser identities, made-up residential IPs in
 *    X-Forwarded-For) is replaced by a plain fetch.
 *  - Every request goes through one function that removes forwarding and
 *    Referer headers and sends OpenPanopticon's own User-Agent, so no
 *    adapter can present itself as someone else.
 *  - The OpenCCTV adapter is left out: its API is restricted to opencctv.org's
 *    own pages.
 *
 * Run from a checkout of OSIRIS (dev-time only; esbuild is not a dependency
 * of OpenPanopticon):
 *
 *   npx esbuild@0.25 --version   # once, to fetch it
 *   node utils/build-osiris-cctv.mjs /path/to/osiris [out-file]
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';

const osiris = path.resolve(process.argv[2] || '../osiris');
const out = path.resolve(process.argv[3] || 'vendor/osiris/cctv.cjs');
const require = createRequire(import.meta.url);
let esbuild;
try { esbuild = require('esbuild'); } catch {
  console.error('esbuild is needed to build this file: npm i --no-save esbuild@0.25');
  process.exit(1);
}

const cctv = path.join(osiris, 'src/app/api/cctv');
if (!fs.existsSync(path.join(cctv, 'route.ts'))) {
  console.error(`not an OSIRIS checkout: ${osiris}`);
  process.exit(1);
}
const commit = (() => {
  try { return execSync('git rev-parse HEAD', { cwd: osiris }).toString().trim(); } catch { return 'unknown'; }
})();

// route.ts keeps the region table and the view-to-region mapping to itself;
// expose them, and nothing of its Next.js handler, through a small entry.
const routeSrc = fs.readFileSync(path.join(cctv, 'route.ts'), 'utf8');
const patched = path.join(cctv, '__op_route.ts');
fs.writeFileSync(patched, `${routeSrc}\nexport { RAW_REGION_FETCHERS as __OP_FETCHERS, getRegionsForBounds as __OP_REGIONS_FOR };\n`);

const entry = path.join(cctv, '__op_entry.ts');
fs.writeFileSync(entry, `
export { __OP_FETCHERS as regionFetchers, __OP_REGIONS_FOR as regionsFor } from './__op_route';
export { TEXAS_DISTRICTS, TXDOT_BASE } from './texas';
export { fetchScotlandPicture } from './scotland';
export { currentFrameUrl as estoniaFrameUrl } from './estonia';
export { currentFrameUrl as singaporeFrameUrl } from './singapore';
export const OSIRIS_COMMIT = ${JSON.stringify(commit)};
`);

const shims = {
  '@/lib/stealthFetch': `
    export function stealthHeaders(extra) { return { ...(extra || {}) }; }
    export function stealthFetch(url, init) { return fetch(url, init); }`,
  'next/server': `
    export const NextResponse = { json: (b, i) => new Response(JSON.stringify(b), i) };
    export class NextRequest extends Request {}`,
  './opencctv': `
    export const TURKEY_BOX = { minLat: 0, maxLat: 0, minLng: 0, maxLng: 0 };
    export async function fetchEastAsiaCameras() { return []; }
    export async function fetchSeAsiaCameras() { return []; }
    export async function fetchWestAsiaCameras() { return []; }
    export async function fetchTurkeyBoxCameras() { return []; }`,
};

const plugin = {
  name: 'openpanopticon-shims',
  setup(build) {
    build.onResolve({ filter: /.*/ }, (args) => {
      if (shims[args.path]) return { path: args.path, namespace: 'op-shim' };
      return undefined;
    });
    build.onLoad({ filter: /.*/, namespace: 'op-shim' }, (args) => ({ contents: shims[args.path], loader: 'js' }));
  },
};

// The one way out to the network for every adapter.
const banner = `/* Generated by utils/build-osiris-cctv.mjs from OSIRIS ${commit}.
 * OSIRIS camera adapters: Copyright (c) 2026 simplifaisoul, MIT licence (see LICENSE beside this file).
 * Do not edit; rebuild instead. */
'use strict';
const __opStrip = new Set(['x-forwarded-for', 'x-real-ip', 'forwarded', 'via', 'referer', 'origin', 'user-agent', 'cookie']);
function __opFetch(input, init = {}) {
  const headers = new Headers(init.headers || {});
  for (const k of [...headers.keys()]) if (__opStrip.has(k.toLowerCase())) headers.delete(k);
  headers.set('User-Agent', globalThis.__OP_CCTV_UA || 'OpenPanopticon');
  const { next, ...rest } = init;
  return globalThis.fetch(input, { ...rest, headers, redirect: rest.redirect || 'follow' });
}`;

try {
  await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    outfile: out,
    tsconfig: path.join(osiris, 'tsconfig.json'),
    plugins: [plugin],
    define: { fetch: '__opFetch' },
    banner: { js: banner },
    legalComments: 'none',
    logLevel: 'warning',
  });
  fs.copyFileSync(path.join(osiris, 'LICENSE'), path.join(path.dirname(out), 'LICENSE'));
  console.log(`wrote ${out} (${(fs.statSync(out).size / 1e6).toFixed(1)} MB) from OSIRIS ${commit}`);
} finally {
  fs.rmSync(patched, { force: true });
  fs.rmSync(entry, { force: true });
}
